#!/usr/bin/env node
// Makes sure this clone's git hooks are installed, so a commit cannot skip the pre-commit checks
// because nobody ran `pre-commit install`.
//
//     node tools/install-hooks.cjs            install the hooks if they are missing
//     node tools/install-hooks.cjs --check    install nothing; say whether they are there
//
// Why this exists. Git hooks live in .git/hooks, which is not part of the repository, so every new
// clone starts without them and `pre-commit install` was a line in CONTRIBUTING.md that had to be
// remembered. A clone without hooks commits anything: on 14 October 2026 a formatting failure
// reached CI that way, and the commit-msg hook that refuses a closing keyword was not running in
// that clone either.
//
// When it runs. `npm ci` and `npm install` run it as the `prepare` script, and `npm test` runs it
// with --check before any test (jest's globalSetup), so a clone whose hooks are missing cannot run
// the tests.
//
// It does nothing, and exits 0, in two cases:
//   - CI is set. CI runs `pre-commit run --all-files` itself and never commits.
//   - This is not a git clone of the repository (a source archive has no hooks to install).
//
// Exit 0: both hooks are installed, or one of the two cases above. Exit 1: they are not, with the
// reason and what to do.
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const HOOKS = ['pre-commit', 'commit-msg'];
// pre-commit writes this line into every hook it installs.
const MARK = 'File generated by pre-commit';
const HOW_TO_GET_IT =
  'pre-commit is a Python tool. Install it with one of:\n' +
  '    brew install pre-commit\n' +
  '    pipx install pre-commit==4.6.2\n' +
  '    uv tool install pre-commit==4.6.2\n' +
  'then run `npm ci` again, or `pre-commit install`.';

const git = (root, args) => {
  const result = spawnSync('git', args, { cwd: root, encoding: 'utf8' });
  return result.status === 0 ? result.stdout.trim() : null;
};

// The repository's own clone: git's top level is this directory. A copy of the files inside some
// other repository is not one, and its hooks are not ours to install.
const isOwnClone = (root) => {
  const top = git(root, ['rev-parse', '--show-toplevel']);
  return top !== null && fs.realpathSync(top) === fs.realpathSync(root);
};

/** The hooks that are not installed by pre-commit in the clone at `root`. */
const missingHooks = (root) =>
  HOOKS.filter((name) => {
    // --git-path gives the right file in a worktree and when core.hooksPath is set.
    const file = git(root, ['rev-parse', '--git-path', `hooks/${name}`]);
    if (file === null) return true;
    try {
      return !fs.readFileSync(path.resolve(root, file), 'utf8').includes(MARK);
    } catch {
      return true;
    }
  });

/**
 * Checks the clone at `root` and, unless `checkOnly`, installs what is missing.
 * Returns { ok, message }. `message` is empty when there is nothing to say.
 */
const ensureHooks = (root, { env = process.env, checkOnly = false } = {}) => {
  if (env.CI) return { ok: true, message: '' };
  if (!isOwnClone(root)) return { ok: true, message: '' };

  const before = missingHooks(root);
  if (before.length === 0) return { ok: true, message: '' };
  if (checkOnly)
    return {
      ok: false,
      message:
        `This clone's git hooks are not installed (missing: ${before.join(', ')}), ` +
        'so a commit here would skip the pre-commit checks.\n' +
        'Run `node tools/install-hooks.cjs`.',
    };

  const install = spawnSync('pre-commit', ['install'], {
    cwd: root,
    encoding: 'utf8',
    env,
  });
  if (install.error)
    return {
      ok: false,
      message: `The git hooks are not installed, and pre-commit was not found to install them.\n${HOW_TO_GET_IT}`,
    };
  const after = missingHooks(root);
  if (install.status !== 0 || after.length > 0)
    return {
      ok: false,
      message:
        `\`pre-commit install\` did not install the git hooks (missing: ${after.join(', ') || 'none'}).\n` +
        `${install.stdout || ''}${install.stderr || ''}`.trim(),
    };
  return { ok: true, message: `Installed the git hooks: ${before.join(', ')}.` };
};

module.exports = { ensureHooks, missingHooks, HOOKS, MARK };

if (require.main === module) {
  const result = ensureHooks(path.join(__dirname, '..'), {
    checkOnly: process.argv.includes('--check'),
  });
  if (result.message) (result.ok ? console.log : console.error)(result.message);
  process.exit(result.ok ? 0 : 1);
}
